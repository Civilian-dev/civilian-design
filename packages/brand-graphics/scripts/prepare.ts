/**
 * First build step: writes `src/kit.ts` (the shape kit, pre-parsed, so the
 * package needs no file access at run time) and copies the source SVGs into
 * a fresh `dist/` for consumers that place pieces themselves.
 * `src/kit.ts` is committed and checked for drift by CI.
 */
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";
import { type Kit, parsePiece } from "../src/compose";

const root = fileURLToPath(new URL("..", import.meta.url));
const src = join(root, "src");
const dist = join(root, "dist");

const svgs = (dir: string) =>
  readdirSync(join(src, dir))
    .filter((f) => f.endsWith(".svg"))
    .sort();

const read = (path: string) =>
  parsePiece(readFileSync(join(src, path), "utf8"), path);

const kit: Kit = {
  shapes: Object.fromEntries(
    svgs("shapes").map((f) => [basename(f, ".svg"), read(`shapes/${f}`)]),
  ),
  mark: read("mark/civilian.svg"),
};

writeFileSync(
  join(src, "kit.ts"),
  `// Generated by scripts/prepare.ts from src/shapes and src/mark. Do not edit.
import type { Kit } from "./compose.js";

export const kit: Kit = ${JSON.stringify(kit, null, 2)};
`,
);

rmSync(dist, { recursive: true, force: true });
for (const dir of ["shapes", "mark"]) {
  mkdirSync(join(dist, dir), { recursive: true });
  for (const f of svgs(dir))
    copyFileSync(join(src, dir, f), join(dist, dir, f));
}
console.log(
  `brand-graphics: wrote src/kit.ts (${Object.keys(kit.shapes).length} shapes and the mark)`,
);
