/**
 * Generate src/preset.ts from the canonical tokens in @civilian-dev/design-tokens.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

type Json = any;

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokensDir = dirname(
  fileURLToPath(import.meta.resolve("@civilian-dev/design-tokens/json")),
);
const readJson = (f: string): Json =>
  JSON.parse(readFileSync(resolve(tokensDir, f), "utf8"));

const refName = (v: unknown): string | undefined =>
  typeof v === "string" ? /^\{([^{}]+)\}$/.exec(v)?.[1] : undefined;

const dimCss = (d: Json) => `${d.value}${d.unit}`;

function colourCss(v: Json): string {
  const [r, g, b] = v.components as number[];
  return v.alpha < 1
    ? `rgb(${Math.round((r as number) * 255)} ${Math.round((g as number) * 255)} ${Math.round((b as number) * 255)} / ${v.alpha})`
    : v.hex;
}

function* leaves(node: Json, path: string[] = []): Generator<[string[], Json]> {
  if (node && typeof node === "object" && "$value" in node) {
    yield [path, node];
    return;
  }
  for (const [k, v] of Object.entries<Json>(node ?? {}))
    if (!k.startsWith("$")) yield* leaves(v, [...path, k]);
}

function put(tree: Json, path: string[], value: Json): void {
  let cur = tree;
  path.forEach((s, i) => {
    if (i === path.length - 1) cur[s] = value;
    else cur = cur[s] ??= {};
  });
}

/** `{colors.x}` references stay as Panda token references. */
const pandaValue = (t: Json): string | number | string[] => {
  const alias = refName(t.$value);
  if (alias) return `{${alias}}`;
  switch (t.$type) {
    case "dimension":
    case "duration":
      return dimCss(t.$value);
    case "cubicBezier":
      return `cubic-bezier(${t.$value.join(", ")})`;
    case "number":
      return t.$value;
    case "fontFamily":
      return t.$value;
    default:
      return t.$value;
  }
};

function shadowValue(layers: Json[]): string {
  return layers
    .map(
      (l) =>
        `${l.inset ? "inset " : ""}${dimCss(l.offsetX)} ${dimCss(l.offsetY)} ${dimCss(l.blur)} ${dimCss(l.spread)} ${l.color}`,
    )
    .join(", ");
}

export function buildPreset(): {
  tokens: Json;
  semanticTokens: Json;
  textStyles: Json;
  breakpoints: Json;
} {
  const light = readJson("tokens.json");
  const dark = readJson("tokens.dark.json");
  const darkMap = new Map<string, Json>(
    [...leaves(dark)].map(([p, t]) => [p.join("."), t]),
  );

  const tokens: Json = {};
  const semantic: Json = { colors: {}, shadows: {} };
  const textStyles: Json = {};
  const breakpoints: Json = {};

  for (const [path, t] of leaves(light)) {
    const [group, ...rest] = path as [string, ...string[]];
    const key = path.join(".");
    if (group === "colors") {
      const alias = refName(t.$value);
      if (alias) {
        const d = darkMap.get(key);
        put(semantic.colors, rest, {
          value: {
            base: `{${alias}}`,
            _dark: d ? `{${refName(d.$value)}}` : `{${alias}}`,
          },
        });
      } else {
        put(tokens, path, { value: colourCss(t.$value) });
      }
    } else if (group === "shadows") {
      const base = shadowValue(t.$value);
      const d = darkMap.get(key);
      put(semantic.shadows, rest, {
        value: { base, _dark: d ? shadowValue(d.$value) : base },
      });
    } else if (group === "textStyles") {
      const v = t.$value;
      put(textStyles, rest, {
        value: {
          fontFamily: v.fontFamily,
          fontSize: v.fontSize,
          fontWeight: v.fontWeight,
          lineHeight: String(v.lineHeight),
          letterSpacing: `${t.$extensions["dev.civilian"].letterSpacing}em`,
        },
      });
    } else if (group === "breakpoints") {
      put(breakpoints, rest, dimCss(t.$value));
    } else if (group === "letterSpacings") {
      put(tokens, path, { value: `${t.$value}em` });
    } else {
      put(tokens, path, { value: pandaValue(t) });
    }
  }
  return { tokens, semanticTokens: semantic, textStyles, breakpoints };
}

function main() {
  const p = buildPreset();
  const body = `// Generated by scripts/generate.ts from @civilian-dev/design-tokens. Do not edit.
import { definePreset } from "@pandacss/dev";

export const civilianPreset = definePreset({
  name: "@civilian-dev/panda-design-preset",
  conditions: {
    // D4: explicit attribute wins; otherwise follow the OS unless the page opts into light.
    dark: {
      '[data-theme="dark"] &': "@slot",
      "@media (prefers-color-scheme: dark)": { ':root:not([data-theme="light"]) &': "@slot" },
    },
  },
  theme: {
    breakpoints: ${JSON.stringify(p.breakpoints, null, 6)},
    tokens: ${JSON.stringify(p.tokens, null, 6)},
    semanticTokens: ${JSON.stringify(p.semanticTokens, null, 6)},
    textStyles: ${JSON.stringify(p.textStyles, null, 6)},
  },
});

export default civilianPreset;
`;
  writeFileSync(resolve(root, "src/preset.ts"), body);
  console.log("generated src/preset.ts");
}

main();
