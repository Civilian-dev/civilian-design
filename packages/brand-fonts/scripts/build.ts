/**
 * Builds `dist/` from the pinned @fontsource packages: woff2 files for pages,
 * OpenType files (.ttf or .otf) decoded from them for renderers that cannot
 * read woff2, each
 * family's licence, an @font-face stylesheet and a typed manifest.
 * Output is committed and deterministic; CI fails if it drifts.
 */
import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { decompress } from "wawoff2";

/** Families as named by `fonts.*` in the design tokens. All SIL OFL 1.1. */
export const FAMILIES = [
  { family: "Poppins", slug: "poppins", token: "fonts.heading", ext: "ttf" },
  {
    family: "Instrument Sans",
    slug: "instrument-sans",
    token: "fonts.body",
    ext: "ttf",
  },
  {
    family: "Monaspace Xenon",
    slug: "monaspace-xenon",
    token: "fonts.mono",
    ext: "otf",
  },
] as const;

/** The first four bytes of each OpenType flavour. */
export const MAGIC = { ttf: 0x00010000, otf: 0x4f54544f } as const;

export const WEIGHTS = [400, 500, 600, 700] as const;

export interface Face {
  family: string;
  weight: number;
  style: "normal";
  /** Paths relative to the package's `dist/`. */
  woff2: string;
  /** TrueType (.ttf) or CFF (.otf) outlines, for renderers. */
  opentype: string;
  licence: string;
}

export function faces(): Face[] {
  return FAMILIES.flatMap(({ family, slug, ext }) =>
    WEIGHTS.map((weight) => {
      const base = `${slug}-latin-${weight}-normal`;
      return {
        family,
        weight,
        style: "normal" as const,
        woff2: `woff2/${base}.woff2`,
        opentype: `opentype/${base}.${ext}`,
        licence: `licences/${slug}-OFL.txt`,
      };
    }),
  );
}

export function fontsCss(list: Face[]): string {
  const blocks = list.map(
    (f) =>
      `@font-face {\n  font-family: "${f.family}";\n  font-style: ${f.style};\n  font-weight: ${f.weight};\n  font-display: swap;\n  src: url("./${f.woff2}") format("woff2");\n}`,
  );
  return `/* Generated by @civilian-dev/brand-fonts. Do not edit. */\n${blocks.join("\n")}\n`;
}

export function indexJs(list: Face[]): string {
  return `// Generated by @civilian-dev/brand-fonts. Do not edit.
import { fileURLToPath } from "node:url";

/** Every face in the package. Paths are relative to this file. */
export const fonts = ${JSON.stringify(list, null, 2)};

/** Absolute path to a file in the package, for renderers that load fonts from disk. */
export function fontPath(file) {
  return fileURLToPath(new URL(\`./\${file}\`, import.meta.url));
}
`;
}

export const INDEX_DTS = `// Generated by @civilian-dev/brand-fonts. Do not edit.
export interface Face {
  family: "Poppins" | "Instrument Sans" | "Monaspace Xenon";
  weight: 400 | 500 | 600 | 700;
  style: "normal";
  /** woff2 file for pages, relative to the package's dist folder. */
  woff2: string;
  /** OpenType file (.ttf, or .otf for Monaspace Xenon) for renderers that cannot read woff2. */
  opentype: string;
  /** The family's SIL Open Font License. */
  licence: string;
}
export declare const fonts: readonly Face[];
/** Absolute path to a file in the package, such as \`fontPath(fonts[0].opentype)\`. */
export declare function fontPath(file: string): string;
`;

async function build(): Promise<void> {
  const root = fileURLToPath(new URL("..", import.meta.url));
  const dist = join(root, "dist");
  const require = createRequire(import.meta.url);
  rmSync(dist, { recursive: true, force: true });
  for (const dir of ["woff2", "opentype", "licences"]) {
    mkdirSync(join(dist, dir), { recursive: true });
  }
  const list = faces();
  for (const { slug, ext } of FAMILIES) {
    const src = dirname(require.resolve(`@fontsource/${slug}/package.json`));
    copyFileSync(join(src, "LICENSE"), join(dist, `licences/${slug}-OFL.txt`));
    for (const f of list.filter((x) => x.woff2.includes(`/${slug}-`))) {
      const name = f.woff2.slice("woff2/".length);
      const woff2 = readFileSync(join(src, "files", name));
      writeFileSync(join(dist, f.woff2), woff2);
      const sfnt = Buffer.from(await decompress(woff2));
      if (sfnt.readUInt32BE(0) !== MAGIC[ext]) {
        throw new Error(`${name}: decoded font is not .${ext}`);
      }
      writeFileSync(join(dist, f.opentype), sfnt);
    }
  }
  writeFileSync(join(dist, "fonts.css"), fontsCss(list));
  writeFileSync(join(dist, "index.js"), indexJs(list));
  writeFileSync(join(dist, "index.d.ts"), INDEX_DTS);
  console.log(`brand-fonts: wrote ${list.length} faces to dist/`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await build();
